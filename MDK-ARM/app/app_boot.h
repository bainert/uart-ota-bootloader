#ifndef __APP_BOOT_H__
#define __APP_BOOT_H__

/*
 * ============================================================================
 *  应用层：与用户（串口助手）交互
 * ----------------------------------------------------------------------------
 *  职责：
 *      - 解析用户指令（START:<len> / INFO）
 *      - 编排升级流程（等待 -> 擦除 -> 接收 -> 校验 -> 跳转）
 *      - 回显进度与错误、断流超时判定
 *  不直接操作 Flash 与串口寄存器，全部通过接口层（int_bootloader.h）完成。
 *
 *  指令表（串口助手 115200 8N1，勾选"发送新行"）：
 *      START:<len>   开始升级，<len> 为固件十进制字节数，如 START:4164
 *      INFO          查询 A 区固件状态
 *
 *  典型流程：
 *      1) 上电/复位，3 秒内任意输入可取消"自动跳转 APP"
 *      2) 发送 START:4164
 *      3) 等回显 READY
 *      4) 再点"发送文件"发送 .bin（保持 256 字节 / 500ms 分包延时）
 *      5) 自动跳转运行
 * ============================================================================
 */

#include <stdint.h>

/* 上电后等待指令的窗口期（A 区已有合法固件时生效） */
#define APP_BOOT_WAIT_MS          3000U
/* 固件传输中"断流"多久判定为失败 */
#define APP_BOOT_RECV_TIMEOUT_MS  3000U
/* 单条指令行的最大长度 */
#define APP_BOOT_CMD_LINE_MAX     32U
/* 每收满多少字节回显一个 '.' */
#define APP_BOOT_DOT_INTERVAL     4096U

void app_boot_init(void);   /* 上电调用一次 */
void app_boot_poll(void);   /* 主循环反复调用 */

#endif /* __APP_BOOT_H__ */
